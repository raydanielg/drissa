# w-* -> Tailwind font-size equivalent for the <i> glyph
$sizeMap = @{
    '2.5' = 'text-[10px]'; '3' = 'text-xs'; '3.5' = 'text-sm'; '4' = 'text-base'
    '5' = 'text-xl'; '6' = 'text-2xl'; '8' = 'text-3xl'; '10' = 'text-4xl'
    '11' = 'text-5xl'; '12' = 'text-6xl'; '14' = 'text-7xl'
}

$svgRx = [regex]::new('<svg\b((?:"[^"]*"|''[^'']*''|[^''">])*)>(.*?)</svg>', 'Singleline')

$files = Get-ChildItem -Recurse $root -Filter *.blade.php
$converted = 0
$skipped   = 0
$unmapped  = @{}

# Pass A: 'icon' => 'M<path>' array values -> 'icon' => 'hgi-<name>'
$iconArrRx = [regex]"'icon'\s*=>\s*'([^']+)'"
$badDyn = @{}

foreach ($f in $files) {
    $content = [IO.File]::ReadAllText($f.FullName)
    $original = $content

    $content = $iconArrRx.Replace($content, [System.Text.RegularExpressions.MatchEvaluator]({
        param($m)
        $v = $m.Groups[1].Value
        if ($v -notmatch '^\s*M' -or $v -match '\{\{|\$') { return $m.Value }
        $k = ($v -replace '\s+', ' ').Trim()
        if ($map.ContainsKey($k)) { return "'icon' => 'hgi-" + $map[$k] + "'" }
        $script:badDyn[$k] = 1
        return $m.Value
    }))

    # Pass B: <svg> whose path is d="{{ expr }}" -> <i class="hgi hgi-stroke-rounded {{ expr }} ...">
    $dynSvgRx = [regex]::new('<svg\b((?:"[^"]*"|''[^'']*''|[^''">])*)>\s*<path[^>]*?d="\{\{\s*(.*?)\s*\}}"[^>]*/>\s*</svg>', 'Singleline')
    $content = $dynSvgRx.Replace($content, [System.Text.RegularExpressions.MatchEvaluator]({
        param($m)
        $attrs = $m.Groups[1].Value
        $expr  = $m.Groups[2].Value
        $cls = ''
        $clsM = [regex]::Match($attrs, 'class="([^"]*)"')
        if ($clsM.Success) { $cls = $clsM.Groups[1].Value }
        $sizeCls = 'text-base'
        $wm = [regex]::Match($cls, '\bw-(\d+(?:\.\d+)?)\b')
        if ($wm.Success -and $sizeMap.ContainsKey($wm.Groups[1].Value)) { $sizeCls = $sizeMap[$wm.Groups[1].Value] }
        $extra = ([regex]::Replace($cls, '\b[wh]-[\w.\[\]%/()''"":?>-]+', ' ') -replace '\s+', ' ').Trim()
        $newCls = ('hgi hgi-stroke-rounded {{ ' + $expr + ' }} ' + $sizeCls + ' ' + $extra -replace '\s+', ' ').Trim()
        return '<i class="' + $newCls + '"></i>'
    }))

    $out = $svgRx.Replace($content, [System.Text.RegularExpressions.MatchEvaluator]({
        param($m)
        $attrs = $m.Groups[1].Value
        $inner = $m.Groups[2].Value

        # Skip dynamic (Blade/JS templated) or non-icon svg (spinners, charts)
        if ($inner -match '\{\{|\$\{|\$\w+\[' -or $inner -match '<circle|<ellipse|<text|<rect|<line') { $script:skipped++; return $m.Value }
        $ds = [regex]::Matches($inner, 'd="([^"]+)"') | ForEach-Object { (($_.Groups[1].Value -replace '\s+', ' ')).Trim() }
        if (-not $ds -or $ds.Count -eq 0) { $script:skipped++; return $m.Value }
        $key = $ds -join '|'
        if (-not $map.ContainsKey($key)) {
            $script:unmapped[$key] = [int]($script:unmapped[$key]) + 1
            $script:skipped++
            return $m.Value
        }

        # size from w-* class
        $cls = ''
        $clsM = [regex]::Match($attrs, 'class="([^"]*)"')
        if ($clsM.Success) { $cls = $clsM.Groups[1].Value }
        $sizeCls = 'text-base'
        $wm = [regex]::Match($cls, '\bw-(\d+(?:\.\d+)?)\b')
        if ($wm.Success -and $sizeMap.ContainsKey($wm.Groups[1].Value)) { $sizeCls = $sizeMap[$wm.Groups[1].Value] }

        # keep all classes except w-*/h-*
        $extra = ([regex]::Replace($cls, '\b[wh]-[\w.\[\]%/()''"":?>-]+', ' ') -replace '\s+', ' ').Trim()

        # preserve aria-hidden / style
        $extraAttrs = ''
        if ($attrs -match 'aria-hidden="[^"]*"') { $extraAttrs += ' ' + $Matches[0] }
        if ($attrs -match 'style="([^"]*)"')    { $extraAttrs += ' style="' + $Matches[1] + '"' }

        $newCls = ('hgi hgi-stroke-rounded hgi-' + $map[$key] + ' ' + $sizeCls + ' ' + $extra -replace '\s+', ' ').Trim()
        $script:converted++
        return '<i class="' + $newCls + '"' + $extraAttrs + '></i>'
    }))

    if ($out -ne $original) { [IO.File]::WriteAllText($f.FullName, $out) }
}

